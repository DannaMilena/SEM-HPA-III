/* ---------- Catalogos ---------- */
CREATE TABLE dbo.Platillos (
    PlatilloID      INT           NOT NULL CONSTRAINT PK_Platillos PRIMARY KEY,
    Nombre          NVARCHAR(100) NOT NULL,
    Disponibilidad  NVARCHAR(20)  NOT NULL CONSTRAINT CK_Platillos_Disp CHECK (Disponibilidad IN (N'Desayuno', N'Almuerzo', N'Cena', N'Siempre')),
    Tipo            NVARCHAR(20)  NOT NULL CONSTRAINT CK_Platillos_Tipo CHECK (Tipo IN (N'Entrada', N'Plato fuerte', N'Postre')),
    Ingredientes    NVARCHAR(300) NULL,
    Calorias        INT           NOT NULL CONSTRAINT CK_Platillos_Cal CHECK (Calorias >= 0),
    Precio          DECIMAL(8,2)  NOT NULL CONSTRAINT CK_Platillos_Precio CHECK (Precio >= 0),
    ImagenNombre    NVARCHAR(200) NULL,        -- ruta relativa del archivo original
    Imagen          VARBINARY(MAX) NULL        -- contenido binario del PNG
);

CREATE TABLE dbo.Bebidas (
    BebidaID        INT           NOT NULL CONSTRAINT PK_Bebidas PRIMARY KEY,
    Nombre          NVARCHAR(100) NOT NULL,
    Tipo            NVARCHAR(20)  NOT NULL CONSTRAINT CK_Bebidas_Tipo CHECK (Tipo IN (N'Caliente', N'Fría')),
    CantidadOz      INT           NOT NULL CONSTRAINT CK_Bebidas_Oz CHECK (CantidadOz > 0),
    Ingredientes    NVARCHAR(300) NULL,
    Calorias        INT           NOT NULL CONSTRAINT CK_Bebidas_Cal CHECK (Calorias >= 0),
    Precio          DECIMAL(8,2)  NOT NULL CONSTRAINT CK_Bebidas_Precio CHECK (Precio >= 0),
    ImagenNombre    NVARCHAR(200) NULL,
    Imagen          VARBINARY(MAX) NULL
);

CREATE TABLE dbo.Ingredientes (
    IngredienteID   INT           NOT NULL CONSTRAINT PK_Ingredientes PRIMARY KEY,
    Nombre          NVARCHAR(100) NOT NULL CONSTRAINT UQ_Ingredientes_Nombre UNIQUE
);

CREATE TABLE dbo.Dietas (
    DietaID         INT           NOT NULL CONSTRAINT PK_Dietas PRIMARY KEY,
    Nombre          NVARCHAR(50)  NOT NULL CONSTRAINT UQ_Dietas_Nombre UNIQUE,
    IconoNombre     NVARCHAR(200) NULL,
    Icono           VARBINARY(MAX) NULL
);

/* ---------- Relaciones N:M ---------- */
CREATE TABLE dbo.PlatilloIngrediente (
    PlatilloID      INT NOT NULL CONSTRAINT FK_PI_Platillo    FOREIGN KEY REFERENCES dbo.Platillos(PlatilloID),
    IngredienteID   INT NOT NULL CONSTRAINT FK_PI_Ingrediente FOREIGN KEY REFERENCES dbo.Ingredientes(IngredienteID),
    CONSTRAINT PK_PlatilloIngrediente PRIMARY KEY (PlatilloID, IngredienteID)
);

CREATE TABLE dbo.BebidaIngrediente (
    BebidaID        INT NOT NULL CONSTRAINT FK_BI_Bebida      FOREIGN KEY REFERENCES dbo.Bebidas(BebidaID),
    IngredienteID   INT NOT NULL CONSTRAINT FK_BI_Ingrediente FOREIGN KEY REFERENCES dbo.Ingredientes(IngredienteID),
    CONSTRAINT PK_BebidaIngrediente PRIMARY KEY (BebidaID, IngredienteID)
);

CREATE TABLE dbo.PlatilloDieta (
    PlatilloID      INT NOT NULL CONSTRAINT FK_PD_Platillo FOREIGN KEY REFERENCES dbo.Platillos(PlatilloID),
    DietaID         INT NOT NULL CONSTRAINT FK_PD_Dieta    FOREIGN KEY REFERENCES dbo.Dietas(DietaID),
    CONSTRAINT PK_PlatilloDieta PRIMARY KEY (PlatilloID, DietaID)
);

CREATE TABLE dbo.BebidaDieta (
    BebidaID        INT NOT NULL CONSTRAINT FK_BD_Bebida FOREIGN KEY REFERENCES dbo.Bebidas(BebidaID),
    DietaID         INT NOT NULL CONSTRAINT FK_BD_Dieta  FOREIGN KEY REFERENCES dbo.Dietas(DietaID),
    CONSTRAINT PK_BebidaDieta PRIMARY KEY (BebidaID, DietaID)
);

/* ---------- Carrito y pedidos ---------- */
-- TipoProducto + ProductoID apuntan a Platillos o Bebidas, por eso no hay FK directa
-- (la validacion la hace sp_AgregarAlCarrito). NombreProducto y PrecioUnitario son
-- una "foto" del momento en que se agrego el producto.
CREATE TABLE dbo.Carrito (
    ItemCarritoID   INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Carrito PRIMARY KEY,
    TipoProducto    NVARCHAR(10)  NOT NULL CONSTRAINT CK_Carrito_Tipo CHECK (TipoProducto IN (N'Platillo', N'Bebida')),
    ProductoID      INT           NOT NULL,
    NombreProducto  NVARCHAR(100) NOT NULL,
    Unidades        INT           NOT NULL CONSTRAINT CK_Carrito_Uni CHECK (Unidades > 0),
    PrecioUnitario  DECIMAL(8,2)  NOT NULL CONSTRAINT CK_Carrito_Precio CHECK (PrecioUnitario >= 0),
    Subtotal        AS (CONVERT(DECIMAL(10,2), Unidades * PrecioUnitario)) PERSISTED,
    CONSTRAINT UQ_Carrito_Producto UNIQUE (TipoProducto, ProductoID)
);

CREATE TABLE dbo.Pedidos (
    PedidoID        INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Pedidos PRIMARY KEY,
    DetallePedido   NVARCHAR(MAX)  NOT NULL,   -- factura en texto
    PrecioTotal     DECIMAL(10,2)  NOT NULL CONSTRAINT CK_Pedidos_Total CHECK (PrecioTotal >= 0),
    FechaPedido     DATETIME2(0)   NOT NULL CONSTRAINT DF_Pedidos_Fecha DEFAULT SYSDATETIME()
);
GO

